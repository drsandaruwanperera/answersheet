const currentRole =
    String(
        sessionStorage.getItem("adminRole") || ""
    )
    .trim()
    .toLowerCase();

const currentUsername =
    String(
        sessionStorage.getItem("adminUsername") || ""
    )
    .trim()
    .toLowerCase();


// -----------------------------------------------------
